void ili9225_draw_char(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg)
{
    if (c < 32 || c > 90) c = ' ';

    const uint8_t *bitmap = font5x7[c - 32];

    for (int col = 0; col < 5; col++) {
        uint8_t line = bitmap[col];
        for (int row = 0; row < 8; row++) {
            if (line & (1 << row)) {
                ili9225_draw_pixel(x + col, y + row, color);
            } else {
                ili9225_draw_pixel(x + col, y + row, bg);
            }
        }
    }

    for (int row = 0; row < 8; row++) {
        ili9225_draw_pixel(x + 5, y + row, bg);
    }
}

void ili9225_draw_string(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg)
{
    while (*str) {
        ili9225_draw_char(x, y, *str, color, bg);
        x += 6;
        str++;
    }
}